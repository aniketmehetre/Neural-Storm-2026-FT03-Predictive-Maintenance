"""Generate a professional PDF maintenance briefing from the fleet agent's Markdown report."""

from __future__ import annotations

import io
import re
from datetime import datetime, timezone
from typing import Any

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

# ── Colours ────────────────────────────────────────────────────────────────────
C_BLUE      = colors.HexColor("#1d4ed8")
C_BLUE_MID  = colors.HexColor("#3b82f6")
C_BLUE_PALE = colors.HexColor("#dbeafe")
C_RED       = colors.HexColor("#dc2626")
C_YELLOW    = colors.HexColor("#b45309")
C_GREEN     = colors.HexColor("#059669")
C_DARK      = colors.HexColor("#0f172a")
C_MUTED     = colors.HexColor("#64748b")
C_BORDER    = colors.HexColor("#e2e8f0")
C_BG        = colors.HexColor("#f8fafc")
C_HDR_BG    = colors.HexColor("#1e3a5f")
C_WHITE     = colors.white

PAGE_W, PAGE_H = A4
MARGIN  = 18 * mm
INNER_W = PAGE_W - 2 * MARGIN


# ── Styles ─────────────────────────────────────────────────────────────────────
def _S() -> dict[str, ParagraphStyle]:
    return {
        "title": ParagraphStyle(
            "title", fontName="Helvetica-Bold", fontSize=26,
            textColor=C_DARK, leading=30, spaceAfter=6,
        ),
        "meta": ParagraphStyle(
            "meta", fontName="Helvetica", fontSize=8.5,
            textColor=C_MUTED, leading=12, spaceAfter=0,
        ),
        "h1": ParagraphStyle(
            "h1", fontName="Helvetica-Bold", fontSize=13,
            textColor=C_BLUE, spaceBefore=14, spaceAfter=4, leading=17,
        ),
        "h2": ParagraphStyle(
            "h2", fontName="Helvetica-Bold", fontSize=11,
            textColor=C_DARK, spaceBefore=10, spaceAfter=3, leading=15,
        ),
        "h3": ParagraphStyle(
            "h3", fontName="Helvetica-BoldOblique", fontSize=9.5,
            textColor=C_MUTED, spaceBefore=6, spaceAfter=2, leading=13,
        ),
        "body": ParagraphStyle(
            "body", fontName="Helvetica", fontSize=9,
            textColor=C_DARK, spaceAfter=4, leading=14,
        ),
        "bullet": ParagraphStyle(
            "bullet", fontName="Helvetica", fontSize=9,
            textColor=C_DARK, spaceAfter=3, leading=13, leftIndent=14,
        ),
        "caption": ParagraphStyle(
            "caption", fontName="Helvetica-Oblique", fontSize=7.5,
            textColor=C_MUTED, spaceAfter=2, leading=11,
        ),
        "kpi_label": ParagraphStyle(
            "kpi_label", fontName="Helvetica", fontSize=7,
            textColor=C_MUTED, alignment=TA_CENTER,
        ),
        "tbl_hdr": ParagraphStyle(
            "tbl_hdr", fontName="Helvetica-Bold", fontSize=7.5,
            textColor=C_WHITE, alignment=TA_LEFT, leading=10,
        ),
        "tbl_cell": ParagraphStyle(
            "tbl_cell", fontName="Helvetica", fontSize=7.5,
            textColor=C_DARK, alignment=TA_LEFT, leading=10,
        ),
    }


# ── Page decorator (header + footer every page) ────────────────────────────────
def _decorator(ts: str):
    def _draw(canvas, doc):
        canvas.saveState()
        # Top accent rule
        canvas.setFillColor(C_BLUE_MID)
        canvas.rect(MARGIN, PAGE_H - 11 * mm, INNER_W, 2, fill=1, stroke=0)
        # Header left label
        canvas.setFont("Helvetica-Bold", 7.5)
        canvas.setFillColor(C_BLUE)
        canvas.drawString(MARGIN, PAGE_H - 9 * mm, "■  ENGINES HEALTH MONITOR")
        # Header right timestamp
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(C_MUTED)
        canvas.drawRightString(PAGE_W - MARGIN, PAGE_H - 9 * mm, ts)
        # Footer rule
        canvas.setStrokeColor(C_BORDER)
        canvas.setLineWidth(0.4)
        canvas.line(MARGIN, 13 * mm, PAGE_W - MARGIN, 13 * mm)
        # Footer text
        canvas.setFont("Helvetica", 6.5)
        canvas.setFillColor(C_MUTED)
        canvas.drawString(
            MARGIN, 9 * mm,
            "Predictive Maintenance · NASA CMAPSS FD001 · "
            "XGBoost (Optuna) · LangGraph Autonomous Fleet Agent",
        )
        canvas.drawRightString(PAGE_W - MARGIN, 9 * mm, f"Page {doc.page}")
        canvas.restoreState()
    return _draw


# ── Cover block ────────────────────────────────────────────────────────────────
def _cover(ts: str, S: dict) -> list:
    """Title + timestamp inside a light-blue bordered box."""
    inner = [
        [Paragraph("Fleet Maintenance Briefing", S["title"])],
        [Paragraph(
            f"Generated by the Autonomous Fleet Diagnostic Agent &nbsp;·&nbsp; {ts}",
            S["meta"],
        )],
    ]
    cover_tbl = Table(inner, colWidths=[INNER_W])
    cover_tbl.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1, -1), C_BLUE_PALE),
        ("LEFTPADDING",   (0, 0), (-1, -1), 12),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 12),
        ("TOPPADDING",    (0, 0), (0, 0),   14),
        ("TOPPADDING",    (0, 1), (0, 1),   0),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 14),
        ("LINEBELOW",     (0, -1), (-1, -1), 2, C_BLUE_MID),
    ]))
    return [Spacer(1, 3 * mm), cover_tbl, Spacer(1, 5 * mm)]


# ── KPI banner ─────────────────────────────────────────────────────────────────
def _kpi_banner(stats: dict, S: dict) -> list:
    items = [
        ("TOTAL\nENGINES",      str(stats.get("total_engines",    "—")), C_BLUE_MID),
        ("🔴  CRITICAL",         str(stats.get("critical_count",   "—")), C_RED),
        ("🟡  WARNING",          str(stats.get("warning_count",    "—")), C_YELLOW),
        ("🟢  HEALTHY",          str(stats.get("healthy_count",    "—")), C_GREEN),
        ("FLEET RMSE\n(cycles)", str(stats.get("fleet_rmse_cycles","—")), C_BLUE),
    ]
    n = len(items)
    cw = INNER_W / n

    row_labels = [Paragraph(lbl, S["kpi_label"]) for lbl, _, _ in items]
    row_values = [
        Paragraph(val, ParagraphStyle(
            f"kv{i}", fontName="Helvetica-Bold", fontSize=18,
            textColor=c, alignment=TA_CENTER,
        ))
        for i, (_, val, c) in enumerate(items)
    ]

    t = Table([row_labels, row_values], colWidths=[cw] * n, rowHeights=[15, 28])
    t.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1, -1), C_BG),
        ("BOX",           (0, 0), (-1, -1), 0.5, C_BORDER),
        ("INNERGRID",     (0, 0), (-1, -1), 0.3, C_BORDER),
        ("TOPPADDING",    (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("VALIGN",        (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return [t, Spacer(1, 5 * mm),
            HRFlowable(width="100%", thickness=0.5, color=C_BORDER, spaceAfter=0),
            Spacer(1, 2 * mm)]


# ── Markdown inline → ReportLab XML ───────────────────────────────────────────
def _inline(text: str) -> str:
    text = re.sub(r"&(?!amp;|lt;|gt;|#)", "&amp;", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"\*(.+?)\*",     r"<i>\1</i>", text)
    text = re.sub(r"`(.+?)`",       r"<font face='Courier'>\1</font>", text)
    return text


# ── Markdown table → ReportLab Table ──────────────────────────────────────────
def _col_widths(headers: list[str]) -> list[float]:
    """Distribute column widths proportionally to header length (min 10%)."""
    raw = [max(len(h.strip()), 4) for h in headers]
    total = sum(raw)
    return [INNER_W * w / total for w in raw]


def _is_sep(row: list[str]) -> bool:
    return bool(row) and all(re.match(r"^:?-{2,}:?$", c.strip()) for c in row if c.strip())


def _md_table(lines: list[str], S: dict) -> Table | None:
    rows_raw: list[list[str]] = []
    for ln in lines:
        ln = ln.strip()
        if not ln.startswith("|"):
            continue
        cells = [c.strip() for c in ln.strip("|").split("|")]
        rows_raw.append(cells)

    # Remove separator rows
    data = [r for r in rows_raw if not _is_sep(r)]
    if len(data) < 2:
        return None

    header, *body = data
    n = len(header)

    def _pad(row: list[str]) -> list[str]:
        return (row + [""] * n)[:n]

    col_w = _col_widths(header)

    tbl_data = [[Paragraph(_inline(c), S["tbl_hdr"]) for c in _pad(header)]]
    for row in body:
        tbl_data.append([Paragraph(_inline(c), S["tbl_cell"]) for c in _pad(row)])

    t = Table(tbl_data, colWidths=col_w, repeatRows=1, hAlign="LEFT")
    t.setStyle(TableStyle([
        # Header
        ("BACKGROUND",    (0, 0), (-1, 0),  C_HDR_BG),
        ("TEXTCOLOR",     (0, 0), (-1, 0),  C_WHITE),
        # Alternating body rows
        ("ROWBACKGROUNDS",(0, 1), (-1, -1), [C_WHITE, C_BG]),
        # Borders
        ("BOX",           (0, 0), (-1, -1), 0.5, C_BORDER),
        ("INNERGRID",     (0, 0), (-1, -1), 0.3, C_BORDER),
        # Padding
        ("TOPPADDING",    (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING",   (0, 0), (-1, -1), 6),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 6),
        ("VALIGN",        (0, 0), (-1, -1), "TOP"),
        ("WORDWRAP",      (0, 0), (-1, -1), "CJK"),
    ]))
    return t


# ── Full Markdown → Flowables ──────────────────────────────────────────────────
def _parse(md: str, S: dict) -> list:
    elems: list = []
    lines = md.splitlines()
    i = 0

    while i < len(lines):
        line  = lines[i]
        strip = line.strip()

        # Horizontal rule
        if re.match(r"^(-{3,}|\*{3,}|_{3,})$", strip):
            elems += [Spacer(1, 3), HRFlowable(
                width="100%", thickness=0.5, color=C_BORDER, spaceAfter=3)]
            i += 1; continue

        # Table block — collect all consecutive pipe lines
        if strip.startswith("|"):
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i])
                i += 1
            t = _md_table(block, S)
            if t:
                elems += [Spacer(1, 4), t, Spacer(1, 6)]
            continue

        # H1
        if strip.startswith("# "):
            elems += [Spacer(1, 4),
                      HRFlowable(width="100%", thickness=1.5,
                                 color=C_BLUE_MID, spaceAfter=3),
                      Paragraph(_inline(strip[2:]), S["h1"])]
            i += 1; continue

        # H2
        if strip.startswith("## "):
            elems.append(Paragraph(_inline(strip[3:]), S["h2"]))
            i += 1; continue

        # H3
        if strip.startswith("### "):
            elems.append(Paragraph(_inline(strip[4:]), S["h3"]))
            i += 1; continue

        # Numbered list
        m = re.match(r"^(\d+)\.\s+(.*)", strip)
        if m:
            num, rest = m.groups()
            elems.append(Paragraph(f"<b>{num}.</b>&nbsp; {_inline(rest)}", S["bullet"]))
            i += 1; continue

        # Bullet
        if re.match(r"^[-*•]\s+", strip):
            rest = re.sub(r"^[-*•]\s+", "", strip)
            elems.append(Paragraph(f"•&nbsp; {_inline(rest)}", S["bullet"]))
            i += 1; continue

        # Empty line
        if not strip:
            if elems and not isinstance(elems[-1], Spacer):
                elems.append(Spacer(1, 4))
            i += 1; continue

        # Regular paragraph
        elems.append(Paragraph(_inline(strip), S["body"]))
        i += 1

    return elems


# ── Public API ─────────────────────────────────────────────────────────────────
def build_pdf(
    markdown_report: str,
    fleet_stats: dict[str, Any] | None = None,
) -> bytes:
    """Convert the fleet agent Markdown report to a polished PDF.

    Args:
        markdown_report: Markdown string from ``FleetMonitoringAgent.run()``.
        fleet_stats:     Dict from ``get_fleet_summary()`` for the KPI banner.

    Returns:
        Raw PDF bytes for ``st.download_button``.
    """
    buf = io.BytesIO()
    ts  = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    S   = _S()

    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=22 * mm, bottomMargin=20 * mm,
        title="Fleet Maintenance Briefing — Engines Health Monitor",
        author="Engines Health Monitor · LangGraph Autonomous Agent",
    )

    elems: list = []
    elems += _cover(ts, S)
    if fleet_stats:
        elems += _kpi_banner(fleet_stats, S)
    elems += _parse(markdown_report, S)

    # Closing note
    elems += [
        Spacer(1, 8 * mm),
        HRFlowable(width="100%", thickness=0.5, color=C_BORDER, spaceAfter=4),
        Paragraph(
            "Generated automatically by the Engines Health Monitor · "
            "4-stage LangGraph pipeline: <b>Sensor Analyst → Diagnostics → "
            "Prioritizer → Report Writer</b>. Based on NASA CMAPSS FD001 · "
            "XGBoost (Optuna-tuned, val RMSE ≈ 17 cycles). "
            "All RUL values in operating cycles.",
            S["caption"],
        ),
    ]

    dec = _decorator(ts)
    doc.build(elems, onFirstPage=dec, onLaterPages=dec)
    buf.seek(0)
    return buf.read()
